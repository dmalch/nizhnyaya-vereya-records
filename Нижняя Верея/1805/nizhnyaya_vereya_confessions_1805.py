from verso.ru.dsl import (CONFESSION_LIST, CensusRole, RecordDefaults, census_records, household,
                          member, page, person)
from verso.ru.dsl.statuses import ECON_PEASANT_FEMALE, ECON_PEASANT_MALE

# Исповедная роспись 1805 г. прихода с. Степанькова, Николаевская церковь. **ГАВО ф. 556
# оп. 111 д. 214, лл. 601–625** (заказ № 5003, получен 28.10.2026; Photos «Степаньково 1805 ИР
# (ГАВО 556-111-214)», pk 3755).
#
# В деле ДВЕ росписи Степанькова за 1805 г.: лл. 601–613 — священника Степана Лебедева (154
# двора; Высоково, Черниченка, Степаньково), лл. 616–625 — № 34, «Роспись Меленковской округи
# села Степанкова церкви святаго Николая Чудотворца священника Тимоѳея Ѳедорова … нынѣшняго
# 1805-го года». Листов 614–615 архив не снимал (они не входят в раздел). Выселенцы 1801 г. в
# Нижнюю Верею стоят во второй росписи, «Економическаго вѣдомства того села крестьяне».
#
# Взят двор 6 — Полуектъ, отец Ивана Полуектова (род Гусевых, `../Гусев.md`).
# ⚠⚠ **ОТЧЕСТВО ПРОТИВОРЕЧИТ РЕВИЗИЯМ.** Роспись пишет ясно «Пулуехтъ Васильевъ, 53», тогда как
# РС-6 1811 и РС-7 1816 гг. — «Полиектъ / Полиевктъ Абрамовъ», а РС-3 1762 г. — Полуехтъ, сынъ
# Абрама Дорофеева. Двор тот же: жена Евдокія Иванова 51 (РС-7: Авдотья 63 ⇒ ок. 1753, здесь ок.
# 1754), сынъ Иванъ 23 и **его жена Прасковья Панфилова, 22** — та, что в РС-10 1857 г. Отчество
# в ИР не исправлено: так в подлиннике, а ревизии трижды пишут «Абрамовъ».
# 🆕 Отчество жены Полуекта — **Иванова**; Прасковья Панфилова замужем за Иваномъ уже в 1805 г.
#
# reviewed=False: прочитано 28.10.2026 по кадру 1190 (л. 616) при ~1.6×; вычитать в Verso.

census = census_records(
    "ГАВО", "556", "111", "214", "Степаньково", 1805,
    *page("616",
          household("6",
                    member(1, person("Пулуехтъ", "Васильевъ"), CensusRole.HEAD, age=53,
                           comment="в ревизиях 1762–1816 гг. — Полуектъ Абрамовъ"),
                    member(2, person("Евдокія", "Иванова"), CensusRole.WIFE, ref_member=1, age=51),
                    member(3, person("Иванъ"), CensusRole.SON, ref_member=1, age=23),
                    member(4, person("Прасковья", "Панфилова"), CensusRole.WIFE, ref_member=3, age=22),
                    ),
          ),
    defaults=RecordDefaults(residence="Нижняя Верея", status_male=ECON_PEASANT_MALE,
                            status_female=ECON_PEASANT_FEMALE),
    reviewed=False,
    **CONFESSION_LIST,
)

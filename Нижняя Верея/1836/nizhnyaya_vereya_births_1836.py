from verso.ru.dsl import (Gender, Month, RecordDefaults, birth, birth_month, birth_records, page,
                          person)
from verso.ru.dsl.statuses import (ECON_PEASANT_FEMALE, ECON_PEASANT_GIRL, ECON_PEASANT_MALE,
                                   ECON_PEASANT_WIFE)

# Метрическая книга Николаевской церкви с. Степанькова за 1836 г., часть первая.
# **ГАВО ф. 556 оп. 106 д. 600, л. 16** (альбом «Степаньково 1836 (ГАВО 556-106-600)»).
# Часть первая — 103 записи, сходится с итогом. ⚠ В 1836 г. писец зовёт деревню
# «**Экономической** деревни Нижней Вѣри» (в 1834 — «Казенной»). НВ в этом году ещё в Степаньковѣ,
# но по чтению агента часть рождений НВ уже записана и в Шиморскомъ — приход менялся постепенно.
#
# reviewed=False: найдено агентом, записи перечитаны по скану.

DEFAULTS = RecordDefaults(residence="Нижняя Верея", status_male=ECON_PEASANT_MALE,
                          status_female=ECON_PEASANT_FEMALE, status_mother=ECON_PEASANT_WIFE)

nizhnyaya_vereya_births_1836 = birth_records(
    "ГАВО", "556", "106", "600", "Нижняя Верея", "Николаевская",
    1836,
    *page("16",
          *birth_month(Month.FEBRUARY,
                       # «Пятаго числа Экономической деревни Нижней Вѣри у крестьянина Алексѣя Никитина и законной
                       # его жены Екатерины Саввиной родился сынъ Василій»; воспріемники «показанной деревни
                       # крестьянинъ Григорій и дѣвка Арина Никитины». ⚠ В РС-10 1857 г. (двор 35) у Алексѣя
                       # Никитина сыновей Василія нет — есть Василій Савватеевъ, 19 лѣтъ, «отъ первой жены»
                       # Савватея. Кто изъ них кто — не решено; этот Василій — Алексѣевъ по метрикѣ
                       birth(6, Gender.MALE, 5, 5,
                             child=person("Василій"),
                             father=person("Алексѣй", "Никитинъ"),
                             mother=person("Екатерина", "Саввина"),
                             god_parent1=person("Григорій", "Никитинъ"),
                             god_parent2=person("Арина", "Никитина", status=ECON_PEASANT_GIRL)),
                       # 🏆 **МЕТРИКА ДМИТРІЯ КСЕНОФОНТОВА** (двор 18 РС-10: «14 л. 4 мѣс» в 1850 ⇒ февраль
                       # 1836 — сходится день в день). «Пятаго числа Экономической деревни Нижней Вѣри у
                       # крестьянина Ксенофонта Иванова и законной его жены Соломіи Максимовой родился сынъ
                       # Дмитрій»; воспріемники «показанной деревни крестьянинъ **Ипполитъ Ефимовъ** и дѣвка
                       # Марѳа Ананьева» — кумовство двух линий Гусевых
                       birth(7, Gender.MALE, 5, 5,
                             child=person("Дмитрій"),
                             father=person("Ксенофонтъ", "Ивановъ"),
                             mother=person("Соломія", "Максимова"),
                             god_parent1=person("Ипполитъ", "Ефимовъ"),
                             god_parent2=person("Марѳа", "Ананьева", status=ECON_PEASANT_GIRL)),
                       ),
          ),
    defaults=DEFAULTS,
    reviewed=False,
)

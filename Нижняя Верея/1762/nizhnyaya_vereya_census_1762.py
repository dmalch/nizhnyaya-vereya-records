from verso.ru.dsl import (CensusRole, Month, RecordDefaults, census_records, household, member,
                          page, person)
from verso.ru.dsl.statuses import ECON_PEASANT_FEMALE, ECON_PEASANT_MALE

# 3-я ревизия 1762 г., сказка «вотчины бывшей Святотроицкой Сергиевой лавры, которая нынѣ въ
# вѣдомствѣ Коллегіи экономіи, Муромскаго уѣзду Унженскаго стану села Степанкова з деревнями»,
# писана въ июнѣ 1762 г. по сенатскому указу 27 генваря 1762 г., «подана июня 15 дня 1762». **ГАВО ф. 301 оп. 5 д. 71, л. 511об (по второй нумерации 527об)**, скан ЭЧЗ 1016.
# Сказка — лл. 511–540об (сканы 1015–1075, «№ 163»; на 540об подписи выборных); альбом Photos
# «Степаньково 1762 РС-3 (ГАВО 301-5-71)».
# Сказка держит три селения: Степанково (лл. 511–521), Высоково (521об–534об), Черниченка
# (535–540); прочитана целиком 12.10.2026, индекс дворов — в `../ARCHIVES.md`.
#
# 🆕 **Второй экземпляр той же сказки № 163 — ГАВО 301-5-68, лл. 746–756об** (сельская часть до итога
# «329 душъ»; альбом «Степанковка 1762 РС (ГАВО 301-5-68)», pk 1064). Дворъ Дорофея — л. 746об–747. В нём
# графа возрастов стоит ровно против имён, тогда как в 301-5-71 она съехала на строку вверх, — по нему
# и взяты возрасты сыновей Абрама.
#
# ⚠⚠ Дело 301-5-71 — это **3-я ревизия 1762–1763 гг., а не 4-я 1782 г.**, как числилось: так на
# обложке («Ревизские сказки 3-й ревизии мещан, казенных и удельных крестьян … Меленковского уезда»)
# и в метаданных ЭЧЗ («20 мая 1762 г. – 23 января 1763 г.»). Реестр дела (сканы 0002–0014) ведёт
# сказки по старой нумерации листов («Вѣдомства коллегіи экономіи села Степанова з деревнями, 5…»).
# Прошлая ревизия по сказке — «послѣдняя 1747 году», то есть 2-я (1744–1747).
#
# 🏆 **ДВОР АБРАМА ДОРОФЕЕВА — ОБЩИЙ ПРЕДОК ОБЕИХ ЛИНИЙ ГУСЕВЫХ.** Отпечаток из РС-6 1811 г. (дворъ 17
# выселенцевъ въ НВ 1801 г.: «Абрамъ Дорофеевъ 65; Абрамовы дѣти Полиектъ 45, Ефимъ 34; Абрама внукъ
# Пантелей Андреевъ 30») сходится по ВСЕМ именам: здесь у Абрама сыновья **Андрей, Полуехтъ,
# Максимъ, Ефимъ**, и возрасты сходятся: Полуехтъ 13 ⇒ ок. 1749 (РС-6: ок. 1750), Ефимъ 2 ⇒ ок. 1760
# (РС-6: ок. 1761). Абрамъ 33 ⇒ род. ок. 1729 — РС-6 даёт 65 въ 1795 г. ⇒ ок. 1730. Отецъ Абрама —
# **Дорофей Андреевъ**, умеръ въ 1759 г.; мать — **Наталья Матвеева** изъ д. Высоково; жена Абрама —
# **Елисавета Яковлева** изъ д. Черниченки (обе деревни той же Муромской вотчины).
#
# reviewed=False: прочитано при 1.9–2.6× по обоим экземплярам.

census = census_records(
    "ГАВО", "301", "5", "71", "Степаньково", 1762,
    *page("511об",
          household(None,
                    # «44 — умеръ въ 1759 году» (возраст по ревизии 1747 г.)
                    member(1, person("Дорофей", "Андреевъ"), CensusRole.HEAD, previous_age=44,
                           departure_year=1759, departure_reason="умер"),
                    # «у него жена Наталья Матвеева дочь 50 лѣтъ, взята оз начиненной Муромской вотчины изъ
                    # деревни Высокова»
                    member(2, person("Наталья", "Матвеева", residence="Высоково"), CensusRole.WIFE, age=50),
                    # «у нихъ сынъ, написанной въ послѣднюю ревизію, Абрамъ — 16 … 33»
                    member(3, person("Абрамъ"), CensusRole.SON, previous_age=16, age=33),
                    # «у него жена Елисавета Яковлева 40 лѣтъ, взята оной же Муромской вотчины изъ деревни
                    # Черниченія» — «40» подтверждён вторым экземпляром
                    member(4, person("Елисавета", "Яковлева", residence="Черничка"), CensusRole.WIFE,
                           ref_member=3, age=40),
                    # «у него дѣти, рожденные послѣ ревизіи» — возрасты по 301-5-68 (л. 746об–747), где графа
                    # стоит против имён; в 301-5-71 те же 15, 13, 7, 2 съехали на строку вверх
                    member(5, person("Андрей"), CensusRole.SON, ref_member=3, age=15),
                    member(6, person("Полуехтъ"), CensusRole.SON, ref_member=3, age=13),
                    member(7, person("Максимъ"), CensusRole.SON, ref_member=3, age=7),
                    member(8, person("Ефимъ"), CensusRole.SON, ref_member=3, age=2),
                    # «дочь дѣвка Анна — мца» (младенецъ, месяцы не названы)
                    member(9, person("Анна"), CensusRole.DAUGHTER, ref_member=3,
                           comment="«мца» — младенец, месяцы не названы"),
                    ),
          ),
    record_day=15,
    record_month=Month.JUNE,
    prev_revision_year=1747,
    defaults=RecordDefaults(status_male=ECON_PEASANT_MALE, status_female=ECON_PEASANT_FEMALE),
    reviewed=False,
)
